//! AI orchestrator — high-level entry points for different call patterns.
//!
//! This module provides the product-layer orchestration that sits above the
//! raw `QueryEngine` and `ApiClient`. It selects models, prompts, and execution
//! strategies based on intent rather than raw parameters.
//!
//! Call patterns:
//! - `run_main_agent`: full interactive agent loop with tools and streaming
//! - `run_side_query`: single-shot non-streaming decision/explanation query
//! - `run_lightweight_query`: fast small-model query for titles, parsing, etc.
//! - `run_forked_agent`: isolated sub-agent with its own context and tool set

use crate::api_client::{ApiClient, ApiError};
use crate::engine::{QueryEngine, SubmitOptions, TerminalReason};
use crate::permission_engine::{ExplainPermissionHook, PermissionEngine};
use crate::permissions::{PermissionChecker, PermissionMode};
use crate::query_profiles::{ModelProfile, PromptProfile, QueryKind, QueryRequest};
use crate::state::SessionState;
use crate::types::{EngineEvent, Message, ModelId, UsageSummary};
use std::path::PathBuf;
use std::sync::Arc;
use tokio::sync::mpsc;

/// Result from a query execution.
#[derive(Debug, Clone)]
pub struct QueryResult {
    /// The text content from the response.
    pub content: String,
    /// Token usage summary.
    pub input_tokens: usize,
    /// Output tokens generated by the model.
    pub output_tokens: usize,
    /// Tokens served from prompt cache.
    pub cache_read_tokens: usize,
    /// Tokens written into prompt cache.
    pub cache_creation_tokens: usize,
}

/// Kinds of background features that run on the forked-agent/background lane.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum BackgroundFeatureKind {
    /// Short activity summary for a sub-agent.
    AgentSummary,
    /// Summary of what happened while the user was away.
    AwaySummary,
    /// Team-wide status aggregation.
    TeamStatus,
    /// Suggest follow-up prompts.
    PromptSuggestion,
    /// Suggest the next best task action.
    NextActionSuggestion,
    /// Generate code documentation.
    MagicDocs,
    /// Generate a codebase overview.
    CodebaseOverview,
    /// Generate a README.
    ReadmeGeneration,
    /// Update session memory in the background.
    SessionMemoryUpdate,
    /// Extract long-term memories in the background.
    MemoryExtraction,
}

/// Request shape for background feature execution.
#[derive(Debug, Clone)]
pub struct BackgroundFeatureRequest {
    /// The background feature being executed.
    pub kind: BackgroundFeatureKind,
    /// System prompt for the background worker.
    pub system_prompt: String,
    /// User prompt describing the task.
    pub user_prompt: String,
    /// Optional parent context inherited from the foreground session.
    pub parent_context: Option<String>,
    /// Optional tool whitelist for the background worker.
    pub allowed_tools: Option<Vec<String>>,
    /// Maximum output tokens.
    pub max_tokens: u32,
    /// Whether the agent is allowed to write files.
    pub writable: bool,
}

/// Errors from orchestrator operations.
#[derive(Debug, thiserror::Error)]
pub enum OrchestratorError {
    /// API-level error.
    #[error("API error: {0}")]
    Api(#[from] ApiError),
    /// Invalid configuration.
    #[error("orchestrator config error: {0}")]
    Config(String),
}

